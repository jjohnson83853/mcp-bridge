func TestProfiledExecutableStatementStartLineOracle(t *testing.T) {
	dir := t.TempDir()
	source := `package core
var initialized = initValue()
func initValue() int { return 7 }
func choose(flag bool) int {
 if flag { return 1 } else { return 2 }
}
func multi() int { first := 1; second := 2; return first + second }
`
	file := filepath.Join(dir, "core.go")
	if err := os.WriteFile(file, []byte(source), 0o600); err != nil {
		t.Fatal(err)
	}
	pkg := Package{ImportPath: "example/core", Dir: dir, GoFiles: []string{"core.go"}}
	profile := []profileEntry{
		{file: "example/core/core.go", block: Block{Start: Position{Line: 5, Column: 2}, End: Position{Line: 5, Column: 22}, Count: 1}},
		{file: "example/core/core.go", block: Block{Start: Position{Line: 7, Column: 18}, End: Position{Line: 7, Column: 32}, Count: 1}},
	}
	got, err := measure([]Package{pkg}, profile)
	if err != nil {
		t.Fatal(err)
	}
	if got.Total != 3 || got.Hit != 2 {
		t.Fatalf("coverage=%+v, want 2/3", got)
	}
}
func TestParseProfileMeasuresZeroStatementBlock(t *testing.T) {
	dir := t.TempDir()
	source := "package core\nfunc empty() {}\nfunc positive() { value := 1; _ = value }\n"
	if err := os.WriteFile(filepath.Join(dir, "core.go"), []byte(source), 0o600); err != nil {
		t.Fatal(err)
	}
	profile := "mode: atomic\n" +
		"example/core/core.go:2.17,2.18 0 0\n" +
		"example/core/core.go:3.19,3.43 1 1\n"
	entries, err := parseProfile([]byte(profile))
	if err != nil {
		t.Fatalf("parseProfile rejected valid zero-statement record: %v", err)
	}
	if len(entries) != 2 {
		t.Fatalf("parsed %d entries, want 2", len(entries))
	}
	got, err := measure([]Package{{ImportPath: "example/core", Dir: dir, GoFiles: []string{"core.go"}}}, entries)
	if err != nil {
		t.Fatal(err)
	}
	if got.Total != 1 || got.Hit != 1 {
		t.Fatalf("coverage = %+v, want 1/1 (zero-statement block excluded)", got)
	}
}
func TestRetainedCoverageOracle(t *testing.T) {
	root := t.TempDir()
	coreDir := filepath.Join(root, "core")
	unusedDir := filepath.Join(root, "unused")
	for _, dir := range []string{coreDir, unusedDir} {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			t.Fatal(err)
		}
	}
	coreSource := "package core\n\nvar initialized = initValue()\n\nfunc initValue() int { return 7 }\n\nfunc init() { initialized++ }\n\nfunc choose(flag bool) int {\n if flag { return 1 } else { return 2 }\n}\n\nfunc multiline() int {\n return choose(\n  true,\n )\n}\n\nfunc sameLine() int { first := 1; second := 2; return first + second }\n\nfunc nested(a, b bool) int {\n if a {\n  if b { return 1 }\n  return 2\n }\n return 3\n}\n"
	linuxSource := "//go:build linux\n\npackage core\n\nfunc targetOnly() int { return 1 }\n"
	generatedSource := "// Code generated by fixture; DO NOT EDIT.\npackage core\n\nfunc generatedOnly() int { return 9 }\n"
	unusedSource := "package unused\n\nvar initialized = true\n\nfunc init() { initialized = false }\n\nfunc neverCalled() int { return 42 }\n"
	for name, content := range map[string]string{"core.go": coreSource, "core_linux.go": linuxSource, "generated.go": generatedSource} {
		if err := os.WriteFile(filepath.Join(coreDir, name), []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	if err := os.WriteFile(filepath.Join(unusedDir, "unused.go"), []byte(unusedSource), 0o600); err != nil {
		t.Fatal(err)
	}
	profile := "mode: atomic\n" +
		"example/core/core.go:5.22,5.34 1 1\n" +
		"example/core/core.go:7.13,7.30 1 1\n" +
		"example/core/core.go:9.28,10.10 1 3\n" +
		"example/core/core.go:10.10,10.22 1 2\n" +
		"example/core/core.go:10.27,10.40 1 1\n" +
		"example/core/core.go:13.22,17.2 1 1\n" +
		"example/core/core.go:19.21,19.71 3 1\n" +
		"example/core/core.go:21.28,22.7 1 1\n" +
		"example/core/core.go:22.7,23.8 1 1\n" +
		"example/core/core.go:23.8,23.20 1 1\n" +
		"example/core/core.go:24.3,24.11 1 0\n" +
		"example/core/core.go:26.2,26.10 1 0\n" +
		"example/core/core_linux.go:5.23,5.35 1 1\n" +
		"example/core/generated.go:4.26,4.38 1 0\n" +
		"example/unused/unused.go:5.13,5.36 1 0\n" +
		"example/unused/unused.go:7.24,7.37 1 0\n"
	entries, err := parseProfile([]byte(profile))
	if err != nil {
		t.Fatal(err)
	}
	packages := []Package{
		{ImportPath: "example/core", Dir: coreDir, GoFiles: []string{"core.go", "core_linux.go", "generated.go"}},
		{ImportPath: "example/unused", Dir: unusedDir, GoFiles: []string{"unused.go"}},
	}
	got, err := measure(packages, entries)
	if err != nil {
		t.Fatal(err)
	}
	if got.Total != 12 || got.Hit != 8 {
		t.Fatalf("retained oracle = %+v, want 8/12 (66.7%%)", got)
	}
}

func TestCoverageFailsClosedForMissingEligibleFileProfile(t *testing.T) {
	dir := t.TempDir()
	file := filepath.Join(dir, "work.go")
	if err := os.WriteFile(file, []byte("package work\nfunc run() { println(\"work\") }\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	pkg := Package{ImportPath: "example/work", Dir: dir, GoFiles: []string{"work.go"}}
	_, err := measure([]Package{pkg}, nil)
	if err == nil || !strings.Contains(err.Error(), "missing eligible profile file: example/work/work.go") {
		t.Fatalf("missing profile error=%v", err)
	}
}

func TestCoverageProfileParsesHalfOpenCoordinates(t *testing.T) {
	got, err := parseProfile([]byte("mode: atomic\nexample/core/core.go:10.2,10.8 1 1\n"))
	if err != nil {
		t.Fatal(err)
	}
	if len(got) != 1 || !within(Position{Line: 10, Column: 2}, got[0].block.Start, got[0].block.End) || within(Position{Line: 10, Column: 8}, got[0].block.Start, got[0].block.End) {
		t.Fatalf("unexpected parsed profile: %+v", got)
	}
	if _, err := parseProfile([]byte("bad\n")); err == nil {
		t.Fatal("invalid profile accepted")
	}
}

func TestParseProfileRejectsMalformedRowsAndPositions(t *testing.T) {
	tests := []struct {
		name, row string
	}{
		{"wrong field count", "example/core.go:1.1,1.2 1"},
		{"invalid count", "example/core.go:1.1,1.2 1 nope"},
		{"invalid statement count", "example/core.go:1.1,1.2 nope 1"},
		{"invalid start position", "example/core.go:x.1,1.2 1 1"},
		{"invalid end position", "example/core.go:1.1,1.x 1 1"},
		{"position range overflow", "example/core.go:999999999999999999999.1,1.2 1 1"},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			if _, err := parseProfile([]byte("mode: atomic\n" + test.row + "\n")); err == nil {
				t.Fatalf("parseProfile accepted %q", test.row)
			}
		})
	}
}

func TestCheckRejectsMissingProfileAndInvalidRoot(t *testing.T) {
	root := t.TempDir()
	if err := os.WriteFile(filepath.Join(root, "go.mod"), []byte("module example.com/sample\n\ngo 1.25.0\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	missingProfile := filepath.Join(root, "missing.out")
	if _, err := Check(root, missingProfile); err == nil || !strings.Contains(err.Error(), "read coverage profile") {
		t.Fatalf("Check missing profile error = %v", err)
	}
	if _, err := Check(filepath.Join(root, "not-a-root"), missingProfile); err == nil || !strings.Contains(err.Error(), "go list packages") {
		t.Fatalf("Check invalid root error = %v", err)
	}
}
